#!/bin/sh
# Прод-энтрипоинт: кешируем конфиг, накатываем миграции, подтягиваем контент
# и запускаем сервер. PORT приходит от платформы (Render/Koyeb его задают);
# по умолчанию 8080.
set -e

php artisan config:cache
php artisan view:cache
php artisan migrate --force

# Разовый бутстрап: создаёт первого админа, если заданы ADMIN_EMAIL/ADMIN_PASSWORD
# и такого пользователя ещё нет (существующего никогда не перезаписывает).
# После первого входа эти переменные лучше убрать.
if [ -n "${ADMIN_EMAIL:-}" ] && [ -n "${ADMIN_PASSWORD:-}" ]; then
    php artisan app:make-admin --from-env || true
fi

# ── Контент при каждом деплое ────────────────────────────────────────────────
# Всё ниже безопасно гонять на каждом старте: команды заполняют только пустые
# поля и не трогают то, что поправлено руками в админке. Так новая пластинка,
# добавленная в репозиторий, доезжает до прода одним пушем — без ручных
# команд в докере.
#
# `|| true` намеренно: если магазин недоступен или база подтормаживает,
# сайт всё равно должен подняться.

# Новые строки каталога из database/seeders/data/vinyls.json
php artisan db:seed --force || true
# Описания для пластинок, у которых их ещё нет
php artisan app:import-descriptions || true
# Жанр, страна, лейбл, состояние — только там, где пусто
php artisan app:fetch-details || true

# ── Принудительное обновление (по флагу, на один деплой) ─────────────────────
# SYNC_CONTENT=1 — перезаписать описания и характеристики значениями из
# репозитория и с сайта магазина, затерев ручные правки. Нужно, когда
# поменялись сами JSON-файлы с описаниями.
if [ "${SYNC_CONTENT:-}" = "1" ]; then
    php artisan app:import-descriptions --overwrite || true
    php artisan app:fetch-details --overwrite || true
fi

# CHECK_AVAILABILITY=1 — обойти магазин и обновить наличие лотов и цены.
# Не включено по умолчанию: это сотни запросов к чужому сайту, и делать их
# при каждом рестарте контейнера незачем.
if [ "${CHECK_AVAILABILITY:-}" = "1" ]; then
    php artisan app:check-availability || true
fi

exec frankenphp php-server --root public/ --listen ":${PORT:-8080}"
